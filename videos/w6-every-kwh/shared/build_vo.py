# Place voice clips on a timeline and time-warp the animation so every line fits.
# Usage: python3 build_vo.py <lines.json> <clip_dir> <old_duration> <out_timing.js> <out_voice.wav>
# Each caption segment [start_i, start_{i+1}) keeps its original length unless the voice needs more,
# in which case it is stretched to voice + 0.35 s. The page maps new time -> old time with WARP.
import json, sys
import numpy as np, soundfile as sf

lines_p, clip_dir, old_dur, out_js, out_wav = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4], sys.argv[5]
lines = json.load(open(lines_p))
SR = 48000
clips = []
for ln in lines:
    a, sr = sf.read(f"{clip_dir}/{ln['id']}.wav", dtype='float32')
    if sr != SR:
        a = np.interp(np.arange(0, len(a) * SR / sr) * sr / SR, np.arange(len(a)), a).astype('float32')
    clips.append(a)
starts = [ln['t'] for ln in lines] + [old_dur]
anchors = [(0.0, 0.0)]
new_t = lines[0]['t']
anchors.append((lines[0]['t'], new_t))
placed = []
for i, ln in enumerate(lines):
    d = len(clips[i]) / SR
    seg_old = starts[i + 1] - ln['t']
    tail = 0.6 if i == len(lines) - 1 else 0.35
    seg_new = max(seg_old, d + tail)
    placed.append((new_t, clips[i]))
    new_t += seg_new
    anchors.append((starts[i + 1], new_t))
new_dur = new_t
voice = np.zeros(int(new_dur * SR) + SR, dtype='float32')
for t, a in placed:
    s = int(t * SR); voice[s:s + len(a)] += a
voice = voice[:int(new_dur * SR)]
peak = np.abs(voice).max(); voice *= 0.89 / peak
sf.write(out_wav, voice, SR)
with open(out_js, 'w') as f:
    f.write('// generated by build_vo.py: [old_time, new_time] anchors\n')
    f.write('window.WARP=' + json.dumps([[round(o, 3), round(n, 3)] for o, n in anchors]) + ';\n')
    f.write(f'window.NEW_DUR={new_dur:.3f};\n')
print('old', old_dur, 'new', round(new_dur, 2))
for o, n in anchors: print(f'{o:6.2f} -> {n:6.2f}')
